# 阶段边界 (用于查询当前处于哪个阶段)
WLTC_PHASES = {
    "Low":         (0, 589),
    "Medium":      (589, 1022),
    "High":        (1022, 1477),
    "Extra-High":  (1477, 1800),
}

def get_wltc_speed(time_s: float) -> float:
    """获取 WLTC 循环中指定时刻的目标车速 (km/h), 线性插值"""
    t = max(0.0, min(time_s, float(len(WLTC_SPEED_KMH) - 1)))
    i = int(t)
    frac = t - i
    if i + 1 >= len(WLTC_SPEED_KMH):
        return WLTC_SPEED_KMH[-1]
    return WLTC_SPEED_KMH[i] + frac * (WLTC_SPEED_KMH[i + 1] - WLTC_SPEED_KMH[i])

def get_wltc_total_duration() -> float:
    """返回 WLTC 循环总时长 (s)"""
    return float(len(WLTC_SPEED_KMH) - 1)

def get_wltc_phase(time_s: float) -> str:
    """返回当前时刻所处的 WLTC 阶段名称"""
    for name, (start, end) in WLTC_PHASES.items():
        if start <= time_s < end:
            return name
    return "Unknown"
